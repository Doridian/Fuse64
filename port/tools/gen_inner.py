#!/usr/bin/env python3
"""The game's names for memory that other names share (docs/PORT.md,
"Names inside another name's object"), reached through a pointer.

  gen_inner.py REGIONS.c ASM_DATA.c OUT.h OUT.c [SCATTER.c]

The fixed-address names (gen/regions.c: aliases into port_rdram) and the
asm data's labels (gen/asm_data.c: aliases into each asm file's struct) are
separate symbols to a host compiler, which takes two symbols for two
objects that don't overlap: it may keep one's value in a register across a
store through the other, or move a load of one past a store to the other.
On the N64 they are one memory (D_800AEE14 is D_800AEDF0[0].unk24, the C
indexes from D_802AFCE8 into D_802AFCF4...).  So in the game's C each such
name is a macro, `(*port_p_NAME)`, a pointer the compiler can't see
through: `extern s32 D_X;` declares `extern s32 (*port_p_D_X);`, and every
use goes through it.  OUT.h has the macros (port_game.h includes it in the
game's C), OUT.c the pointers.

Every name of both kinds is one, but those whose address the C uses in a
static initializer (which needs a constant: EXCLUDE) and the absolute
ones (segment and physical addresses).
"""
import re
import sys

# names whose address a static initializer of the game's C takes
EXCLUDE = {
    "D_80300000",   # 40300.c: the sbrk pointer's start
    "D_802AD120",   # 80580.c: the audio configs
}


def names(path):
    out = []
    for line in open(path):
        m = re.search(r'\.set " PORT_ULP "(D_[0-9A-Za-z_]+), " PORT_ULP "(port_rdram|port_asm_|port_o_|port_scatter_arena)',
                      line)
        if m:
            out.append(m.group(1))
    return out


def main():
    regions, asm_data, out_h, out_c = sys.argv[1:5]
    # (the scattered layout: gen/scatter.c has the aliases)
    extra = [n for p in sys.argv[5:] for n in names(p)]
    ns = sorted(set(names(regions) + names(asm_data) + extra) - EXCLUDE)
    h = ["/* Generated by port/tools/gen_inner.py (docs/PORT.md, \"Names inside another name's object\"). */",
         "#ifndef PORT_INNER_H", "#define PORT_INNER_H"]
    h += ["#define %s (*port_p_%s)" % (n, n) for n in ns]
    h.append("#endif")
    c = ["/* Generated by port/tools/gen_inner.py. */"]
    c += ["extern char %s[];" % n for n in ns]
    c += ["void *port_p_%s = %s;" % (n, n) for n in ns]
    for path, text in ((out_h, h), (out_c, c)):
        new = "\n".join(text) + "\n"
        try:
            old = open(path).read()
        except OSError:
            old = None
        if old != new:
            open(path, "w").write(new)


if __name__ == "__main__":
    main()
