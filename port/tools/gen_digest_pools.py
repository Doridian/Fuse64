#!/usr/bin/env python3
"""The gameplay digest's pools as the host lays them out (docs/PORT.md,
"The object pools").

  gen_digest_pools.py OUT.c [--decls DECLS.json REGIONS.json ASM_DATA.json]

port/host/digest.c's POOL table names each pool's array, its entries and
the N64's stride, and its specs give the fields at their N64 offsets.
Where pointers are 4 bytes the host's layout is the N64's, and OUT.c says
so (no maps).  Where they are 8 (--decls: decls.py's JSON, and gen_regions.py's
and asm2c.py's objects, which say which type each array was laid out by),
OUT.c has, for each pool and for D_800AEDF0 (the `e` a pointer may point
into): the host's stride, the host offset of each N64 offset (0xFFFF
inside a pointer), the N64 offset of each host offset (for a pointer into
an entry, written at its N64 offset) and the N64 offsets where a pointer
begins (read as wide as the host's).  So digest.c writes every field as
the N64 has it, and a 64-bit host's digest is the emulator's.
"""
import argparse
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import layouts  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NONE = 0xFFFF


def pools():
    """digest.c's POOL table: [(key, symbol, entries, N64 stride)], then D_800AEDF0's"""
    src = open(os.path.join(ROOT, "port/host/digest.c")).read()
    out = [(k, s, int(n, 0), int(st, 0))
           for k, s, n, st in re.findall(r'POOL\(\s*"(\w+)",\s*(D_[0-9A-F]+),\s*(\w+),\s*(\w+),', src)]
    if not out:
        sys.exit("port/host/digest.c: no POOL entries found")
    return out + [("e", "D_800AEDF0", 5, 0xC8)]


def maps(lay, objs, key, sym, n, stride):
    """(host stride, host[stride], n64[host stride], pointer offsets) or None (the N64's layout)"""
    o = objs.get(sym)
    if o is None or not o.get("type"):
        if o is not None and o.get("size") not in (None, o.get("n64size")):
            sys.exit("%s (%s): laid out by no type, but %s bytes, not %s" % (sym, key, o["size"], o["n64size"]))
        return None
    f, t = o.get("cfile", o["file"]), o["type"]      # (asm2c.py's: the C file the type is from)
    m = re.match(r"^(.*?)\s*\[(\d+)\]$", t)
    if not m or int(m.group(2)) < n:
        sys.exit("%s (%s): its type %s isn't an array of %d" % (sym, key, t, n))
    elem = m.group(1)
    s32, s64 = lay.size(f, elem, 32), lay.size(f, elem, 64)
    if s32 != stride:
        sys.exit("%s (%s): %s is %s bytes on the N64, the pool's stride %#x" % (sym, key, elem, s32, stride))
    if s64 == s32:
        return None
    host = [NONE] * stride
    back = [NONE] * s64
    for off in range(stride):
        h = lay.host_off(f, elem, off)
        if h is not None:
            host[off] = h
            back[h] = off
    return s64, host, back, sorted(set(lay.pointers(f, elem)))


def table(name, vals):
    rows = [", ".join("0x%X" % v for v in vals[i:i + 12]) for i in range(0, len(vals), 12)]
    return "static const uint16_t %s[%d] = {\n    %s\n};\n" % (name, len(vals), ",\n    ".join(rows))


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("out")
    p.add_argument("--decls", nargs=3, metavar=("DECLS", "REGIONS", "ASM_DATA"))
    a = p.parse_args()
    lay, objs = None, {}
    if a.decls:
        full = json.load(open(a.decls[0]))
        lay = layouts.Layouts(full)
        for path in a.decls[1:]:
            for o in json.load(open(path))["objects"]:
                objs[o["name"]] = o
    out = ["/* generated by port/tools/gen_digest_pools.py: the digest's pools as the host lays",
           "   them out (port/host/digest.c; docs/PORT.md, \"The object pools\") */",
           "#include <stddef.h>", "#include <stdint.h>", "",
           "struct port_digest_layout {", "    const char *key;",
           "    unsigned stride;          /* the host's */",
           "    const uint16_t *host;     /* N64 offset -> host offset (NULL: the N64's layout) */",
           "    const uint16_t *n64;      /* host offset -> N64 offset */",
           "    const uint16_t *ptrs;     /* the N64 offsets where a pointer begins, 0xFFFF last */",
           "};", ""]
    rows = []
    for key, sym, n, stride in pools():
        m = maps(lay, objs, key, sym, n, stride) if lay else None
        if m is None:
            rows.append('    { "%s", 0x%X, NULL, NULL, NULL },' % (key, stride))
            continue
        s64, host, back, ptrs = m
        out.append("/* %s: %s's %s */" % (key, sym, objs[sym]["type"]))
        out.append(table("host_%s" % key, host))
        out.append(table("n64_%s" % key, back))
        out.append(table("ptrs_%s" % key, ptrs + [NONE]))
        rows.append('    { "%s", 0x%X, host_%s, n64_%s, ptrs_%s },' % (key, s64, key, key, key))
    out.append("const struct port_digest_layout port_digest_layouts[] = {")
    out += rows
    out.append("    { NULL, 0, NULL, NULL, NULL },")
    out.append("};")
    text = "\n".join(out) + "\n"
    if not os.path.exists(a.out) or open(a.out).read() != text:
        open(a.out, "w").write(text)


if __name__ == "__main__":
    main()
