#!/usr/bin/env python3
"""The overlays' table for the port (docs/PORT.md, "Overlays").

  gen_overlays.py OUT.c [--markers DIR]

Every overlay is linked in.  Loading one (40FB0.c's func_8022691C, port/
src/overlay.c) puts its .data back as it was at startup and clears its
.bss, which is what inflating it gave on the N64, and calls its entry
(func_ovlBB_EE_80043000).  Where an overlay's variables are is found one
of two ways:

- sections (ELF): its C is compiled with port/include/port_ovl_section.h,
  which puts its variables (function-scope statics too) in sections of
  their own, bm64d_<overlay> and bm64b_<overlay>, which the linker's
  __start_/__stop_ names bound;
- markers (--markers: WebAssembly, where `#pragma clang section` isn't
  taken, and the other object formats): DIR/<overlay>_begin.c and _end.c
  each define a variable with an initializer and one without, and the
  build compiles and links each overlay's C between its two, so that the
  linker, which keeps the input files' data in their order, puts the
  overlay's .data between the begin and end markers' and its .bss between
  theirs.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    out = sys.argv[1]
    markers = sys.argv[3] if len(sys.argv) > 3 and sys.argv[2] == "--markers" else None
    ovls = sorted(d for d in os.listdir(os.path.join(ROOT, "src", "overlays")) if d.startswith("ovl_"))
    o = ["/* Generated by port/tools/gen_overlays.py (docs/PORT.md, \"Overlays\"). */",
         "#include \"port_overlay.h\"", ""]
    for n in ovls:
        bb, ee = n[4:6], n[7:9]
        o.append("void *func_ovl%s_%s_80043000(void);" % (bb, ee))
        if markers:
            for k in "db":
                for e in "01":
                    o.append("extern char port_%s_%s%s;" % (n, k, e))
        else:
            for k in "db":
                o.append("extern char __start_bm64%s_%s[] __attribute__((weak));" % (k, n))
                o.append("extern char __stop_bm64%s_%s[] __attribute__((weak));" % (k, n))
    o.append("")
    o.append("const PortOverlay port_overlays[] = {")
    for n in ovls:
        bb, ee = n[4:6], n[7:9]
        if markers:
            o.append("    { \"%s\", 0x%s, 0x%s, func_ovl%s_%s_80043000, &port_%s_d0 + 1, &port_%s_d1, "
                     "&port_%s_b0 + 1, &port_%s_b1 }," % (n, bb, ee, bb, ee, n, n, n, n))
        else:
            o.append("    { \"%s\", 0x%s, 0x%s, func_ovl%s_%s_80043000, __start_bm64d_%s, __stop_bm64d_%s, "
                     "__start_bm64b_%s, __stop_bm64b_%s }," % (n, bb, ee, bb, ee, n, n, n, n))
    o.append("};")
    o.append("const unsigned port_noverlays = %d;" % len(ovls))
    open(out + ".tmp", "w").write("\n".join(o) + "\n")
    os.replace(out + ".tmp", out)
    if markers:
        os.makedirs(markers, exist_ok=True)
        for n in ovls:
            for e, which in (("0", "begin"), ("1", "end")):
                p = os.path.join(markers, "%s_%s.c" % (n, which))
                s = ("/* Generated by port/tools/gen_overlays.py: overlay %s's %s marker. */\n"
                     "__attribute__((used)) char port_%s_d%s = 1;\n"
                     "__attribute__((used)) char port_%s_b%s;\n" % (n, which, n, e, n, e))
                if not os.path.exists(p) or open(p).read() != s:
                    open(p, "w").write(s)


if __name__ == "__main__":
    main()
