#!/usr/bin/env python3
"""port/include/port_types.h from port/tools/port_types.txt (docs/PORT.md,
"Where pointers are 8 bytes").

    gen_port_types.py [--check]

Each line of port_types.txt is a game object the C reaches by N64 offset
(m2c's M2C_FIELD) in a file that has no type for it:

    NAME SIZE OFF:TYPE...   # what it is

NAME is Port_ and the address or the type of the game's that it is, SIZE
its N64 size, and each OFF:TYPE a pointer at that N64 offset to TYPE (void
for no type the port needs, NAME[] for an array).  The struct is the
pointers and, between them, the N64's bytes as `u8 unkXX[n]`: whatever the
C reads there, PORT_FIELD reaches it by its N64 offset within the run,
and each pointer is as wide as the host's.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "port", "tools", "port_types.txt")
OUT = os.path.join(ROOT, "port", "include", "port_types.h")


def main():
    check = "--check" in sys.argv
    o = ["/*",
         " * Generated by port/tools/gen_port_types.py from port/tools/port_types.txt:",
         " * the game's objects that the C reaches by N64 offset (m2c's M2C_FIELD) in",
         " * a file that has no type for them, as the port lays them out: the",
         " * pointers as wide as the host's, the N64's bytes between them",
         " * (docs/PORT.md, \"Where pointers are 8 bytes\").  Included by",
         " * include/structs.h under TARGET_PC.",
         " */",
         "#ifndef PORT_TYPES_H", "#define PORT_TYPES_H", ""]
    types = []
    for line in open(SRC):
        line, _, comment = line.partition("#")
        f = line.split()
        if not f:
            continue
        types.append((f[0], int(f[1], 0), f[2:], comment.strip()))
    for name, _, _, _ in types:
        o.append("typedef struct %s %s;" % (name, name))
    o.append("")
    for name, size, ptrs, comment in types:
        if comment:
            o.append("/* %s */" % comment)
        o.append("struct %s {" % name)
        pos = 0
        for p in sorted(ptrs, key=lambda x: int(x.split(":")[0], 16)):
            off, t = p.split(":")
            off = int(off, 16)
            if off < pos or off % 4:
                sys.exit("%s: a pointer at 0x%X" % (name, off))
            if off > pos:
                o.append("    /* 0x%02X */ u8 unk%X[0x%X];" % (pos, pos, off - pos))
            ct = "void *" if t == "void" else "%s *" % t
            o.append("    /* 0x%02X */ %sunk%X;" % (off, ct, off))
            pos = off + 4
        if size > pos:
            o.append("    /* 0x%02X */ u8 unk%X[0x%X];" % (pos, pos, size - pos))
        o.append("}; /* N64 size 0x%X */" % size)
        o.append("")
    o.append("#endif")
    text = "\n".join(o) + "\n"
    if check:
        if not os.path.exists(OUT) or open(OUT).read() != text:
            sys.exit("port_types.h is out of date: port/tools/gen_port_types.py")
        return
    open(OUT, "w").write(text)


if __name__ == "__main__":
    main()
