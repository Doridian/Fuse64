#!/usr/bin/env python3
"""The scattered layout (docs/PORT.md, "The scattered layout"): every
fixed-address name and every asm data label in a place of its own.

  gen_scatter.py SEED REGIONS_objects.json ASM_objects.json [--decls DECLS.json] OUT.c

The N64 layout (-DPORT_LAYOUT=n64) keeps what the N64 has at fixed
addresses as one buffer laid out as RDRAM (gen/regions.c) and each asm
data file as one struct (gen/asm_data.c), and the default layout gives
each object the N64's room up to the next declared name, so that a name
reached through its neighbour (past an end, before a start, an index past
a too-small declaration, a range cleared from one name to another) still
reaches what the N64 has there.
This build takes that away: each object (a name with its declared size, or
its room to the next name where no declaration has a size) goes in
port_scatter_arena in an order SEED shuffles, with padding before it of 16
to 2048 bytes plus the size of the one before (up to 16 KB: an index the
N64 had room for lands in padding), keeping its offset modulo 16 (4 KB for
objects of 4 KB or more).  A name inside another object (a member's or an
element's own name, a label inside a typed table) stays inside it, at its
host offset.  At startup each asm .data label's bytes are copied from its
file's struct (asm2c.py --scatter: the startup image; port_scatter_copy,
after the ROM's data is filled in) and (a constructor) the padding, and all of port_rdram, which nothing should reach any more,
are filled with PORT_SCATTER_POISON (0xA5) and, under AddressSanitizer,
poisoned, so that each access there is reported with its place.

OUT's _map.json is the layout, for port/tools/scatter_list.py; OUT's
_report.txt the static report: the names inside other objects (with the
files that use them) and the objects of unknown size.
"""
import json
import os
import random
import sys

POISON = 0xA5
# (D_80300000, the last name: gmalloc's arena; twice that where pointers
# are 8 bytes, --decls: port_game.h's PORT_SBRK_SIZE)
SBRK_SIZE = 0x100000
WORK_FROM, WORK_END = 0x80063000, 0x800BEA60    # the work area 40040.c clears


def main():
    args = sys.argv[1:]
    decls = None
    if "--decls" in args:
        i = args.index("--decls")
        decls = json.load(open(args[i + 1]))
        del args[i:i + 2]
    seed, reg_p, asm_p, out = args
    reg, asm = json.load(open(reg_p)), json.load(open(asm_p))
    bases = dict(asm["bases"])
    entries = [dict(o, kind="region") for o in reg["objects"]] + [dict(o, kind="asm") for o in asm["objects"]]
    bybase = {}
    for e in entries:
        bybase.setdefault(e["base"], []).append(e)
    def used(n):
        """whether the game's C declares n (else only the asm data's words name it)"""
        return not decls or any(d["kind"] == "var" for d in decls["names"].get(n, []))

    objects, inner = [], []     # objects: placed; inner: (entry, container, offset in it)
    for base, es in bybase.items():
        es.sort(key=lambda e: (e["hoff"], "inside" in e))
        cur = None
        for i, e in enumerate(es):
            if cur is not None and (e.get("inside") or e["hoff"] < cur["hoff"] + cur["size"]):
                inner.append((e, cur, e["hoff"] - cur["hoff"]))
                continue

            def room(only_used):
                nxt = [x["hoff"] for x in es[i + 1:] if x["hoff"] > e["hoff"] and (used(x["name"]) or not only_used)]
                if nxt:
                    return nxt[0] - e["hoff"]
                if base in bases:
                    return bases[base] - e["hoff"]
                if e["name"] == "D_80300000":
                    return SBRK_SIZE * (2 if decls else 1)
                return e["room"]
            hroom = room(False)
            e["hroom"] = hroom
            e["unsized"] = e.get("size") is None and not e.get("end")
            # (where no declaration has a size, or one is `T x[]`, the object
            # runs to the next name the C uses: the names between that only
            # the asm data names are inside it)
            if e.get("end"):
                e["size"] = 0
            elif e["unsized"] or e.get("incomplete"):
                e["size"] = max(e.get("size") or 0, room(True))
            if base in bases and not e.get("bss"):
                e["copy"] = max(0, min(e["size"], bases[base] - e["hoff"]))
            cur = e
            objects.append(e)
    rnd = random.Random(int(seed))
    order = objects[:]
    rnd.shuffle(order)
    off, prev = 0, 0
    for e in order:
        pad = rnd.randint(16, 2048) + min(prev, 16384)
        a = 0x1000 if e["size"] >= 0x1000 else 16
        phase = e["hoff"] % a
        o = off + pad
        o += (phase - o) % a
        e["off"] = o
        off = o + e["size"]
        prev = max(e["size"], e.get("hroom", 0))
    total = (off + 4096 + 0x1FFF) & ~0x1FFF

    c = ["/* Generated by port/tools/gen_scatter.py (docs/PORT.md, \"The scattered layout\"): seed %s. */" % seed,
         "#include <stdint.h>", "#include <string.h>", "#include \"port_game.h\"", "",
         "uint8_t port_scatter_arena[0x%X] __attribute__((aligned(0x2000)));" % total,
         "extern uint8_t port_rdram[];", ""]
    for b in sorted(bases):
        c.append("extern uint8_t %s[];" % b)
    for e in sorted(order, key=lambda e: e["off"]):
        c.append("__asm__(\".globl \" PORT_ULP \"%s\\n.set \" PORT_ULP \"%s, \" PORT_ULP \"port_scatter_arena + 0x%X\\n\");"
                 % (e["name"], e["name"], e["off"]))
    for e, cont, d in inner:
        c.append("__asm__(\".globl \" PORT_ULP \"%s\\n.set \" PORT_ULP \"%s, \" PORT_ULP \"port_scatter_arena + 0x%X\\n\");"
                 % (e["name"], e["name"], cont["off"] + d))
    c.append("")
    c.append("static const struct { uint32_t off; const uint8_t *src; uint32_t n; } copies[] = {")
    ncopy = 0
    for e in sorted(order, key=lambda e: e["off"]):
        if e.get("copy"):
            c.append("    { 0x%X, %s + 0x%X, 0x%X }, /* %s */" % (e["off"], e["base"], e["hoff"], e["copy"], e["name"]))
            ncopy += 1
    c.append("    { 0, 0, 0 }")
    c.append("};")
    # 40040.c clears the work area: each of its variables
    c.append("void port_clear_work_area(void) {")
    for e in sorted(order, key=lambda e: e["n64"]):
        if e["kind"] == "region" and WORK_FROM <= e["n64"] < WORK_END and e["size"]:
            c.append("    memset(port_scatter_arena + 0x%X, 0, 0x%X); /* %s */" % (e["off"], e["size"], e["name"]))
    c.append("}")
    gaps, pos = [], 0
    for e in sorted(order, key=lambda e: e["off"]):
        if e["off"] > pos:
            gaps.append((pos, e["off"] - pos))
        pos = max(pos, e["off"] + e["size"])
    gaps.append((pos, total - pos))
    c.append("static const uint32_t gaps[][2] = {")
    c.extend("    { 0x%X, 0x%X }," % g for g in gaps)
    c.append("};")
    # the objects by offset, for the check's reports (port/host/scatter_check.c)
    c.append("typedef struct { const char *name; uint32_t off, size, n64, n64size; } PortScatterObj;")
    c.append("const PortScatterObj port_scatter_objs[] = {")
    for e in sorted(order, key=lambda e: e["off"]):
        c.append("    { \"%s\", 0x%X, 0x%X, 0x%X, 0x%X }," % (e["name"], e["off"], e["size"], e["n64"],
                                                         e.get("n64size") or 0))
    c.append("    { 0, 0x%X, 0, 0, 0 }" % total)
    c.append("};")
    c.append("const unsigned port_scatter_nobjs = %d;" % len(order))
    # the same as port/src/memory.c's objects (the default layout's table):
    # each one's place, size, N64 address and offset in the N64 layout's
    # port_rdram (the image), all of them in port_region_objs
    c.append("typedef struct { uint8_t *p; uint32_t size, n64, img; } PortObj;")
    c.append("const PortObj port_region_objs[] = {")
    nobj = 0
    for e in sorted(order, key=lambda e: e["off"]):
        if e["size"]:
            img = e["hoff"] if e["kind"] == "region" and e["base"] == "port_rdram" else 0xFFFFFFFF
            c.append("    { port_scatter_arena + 0x%X, 0x%X, 0x%X, 0x%X }," % (e["off"], e["size"], e["n64"], img))
            nobj += 1
    c.append("};")
    c.append("const unsigned port_region_nobjs = %d;" % nobj)
    c.append("const PortObj port_asm_objs[1];")
    c.append("const unsigned port_asm_nobjs = 0;")
    c += [
        "",
        "#ifdef PORT_SCATTER_CHECK",
        "void port_scatter_bad(void *p, unsigned long n);",
        "#define POISON(p, n) port_scatter_bad(p, n)",
        "#elif defined(__has_feature)",
        "#if __has_feature(address_sanitizer)",
        "#include <sanitizer/asan_interface.h>",
        "#define POISON(p, n) ASAN_POISON_MEMORY_REGION(p, n)",
        "#endif",
        "#endif",
        "#ifndef POISON",
        "#define POISON(p, n) ((void)0)",
        "#endif",
        "#ifndef PORT_SCATTER_POISON",
        "#define PORT_SCATTER_POISON 0x%X" % POISON,
        "#endif",
        "",
        "/* the asm .data labels' bytes, from their files' structs: after",
        "   host_rom_fill, which gives those structs the ROM's data (main.c's",
        "   load_rom; docs/PORT.md, \"The ROM's data\") */",
        "void port_scatter_copy(void) {",
        "    unsigned i;",
        "    for (i = 0; copies[i].n; i++)",
        "        memcpy(port_scatter_arena + copies[i].off, copies[i].src, copies[i].n);",
        "}",
        "",
        "/* (before anything of the game's runs: AddressSanitizer's own",
        "   constructors, which make the globals accessible, come first) */",
        "__attribute__((constructor(101))) static void port_scatter_init(void) {",
        "    unsigned i;",
        "    for (i = 0; i < sizeof gaps / sizeof gaps[0]; i++) {",
        "        memset(port_scatter_arena + gaps[i][0], PORT_SCATTER_POISON, gaps[i][1]);",
        "        POISON(port_scatter_arena + gaps[i][0], gaps[i][1]);",
        "    }",
        "    memset(port_rdram, PORT_SCATTER_POISON, 0x800000);",
        "    POISON(port_rdram, 0x800000);",
        "}",
        ""]
    open(out + ".tmp", "w").write("\n".join(c) + "\n")
    os.replace(out + ".tmp", out)

    # the layout, for scatter_list.py
    m = {"seed": int(seed), "arena": total, "objects": [], "inner": []}
    for e in sorted(order, key=lambda e: e["off"]):
        m["objects"].append({k: e.get(k) for k in ("name", "kind", "n64", "n64size", "size", "room", "hroom", "off",
                                                    "unsized", "type", "file", "base", "hoff")})
    for e, cont, d in inner:
        m["inner"].append({"name": e["name"], "kind": e["kind"], "n64": e["n64"], "in": cont["name"], "at": d,
                           "n64at": e["n64"] - cont["n64"]})
    json.dump(m, open(out[:-2] + "_map.json", "w"), indent=0)

    # the static report
    def users(n):
        if not decls:
            return ""
        fs = sorted({d["file"] for d in decls["names"].get(n, []) if d["kind"] == "var"})
        return " ".join(fs)
    r = ["# names inside another object (%d): name, kind, the object, N64 offset in it, host offset, the files "
         "that declare the name" % len(inner)]
    for e, cont, d in sorted(inner, key=lambda x: x[0]["n64"]):
        r.append("%s %s in %s +0x%X (here +0x%X): %s" % (e["name"], e["kind"], cont["name"], e["n64"] - cont["n64"], d,
                                                       users(e["name"]) or "-"))
    ends = [e for e in objects if e.get("end")]
    r.append("")
    r.append("# names that are no object (an end, a stack's top, a base of another's index): no room (%d)" % len(ends))
    for e in sorted(ends, key=lambda e: e["n64"]):
        r.append("%s %s: %s" % (e["name"], e["kind"], users(e["name"]) or "-"))
    uns = [e for e in objects if e["unsized"]]
    r.append("")
    r.append("# objects no declaration gives a size (%d): their room to the next name" % len(uns))
    for e in sorted(uns, key=lambda e: e["n64"]):
        r.append("%s %s 0x%X: %s" % (e["name"], e["kind"], e["size"], users(e["name"]) or "-"))
    r.append("")
    r.append("# %d objects, %d copied, arena 0x%X bytes" % (len(objects), ncopy, total))
    open(out[:-2] + "_report.txt", "w").write("\n".join(r) + "\n")


if __name__ == "__main__":
    main()
